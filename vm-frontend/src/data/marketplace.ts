// Marketplace Data - Services, Bookings, Providers

export interface MarketplaceService {
  id: string;
  title: string;
  description: string;
  full_description: string;
  category: string;
  price_range: { min: number; max: number };
  currency: string;
  provider_id: string;
  provider_name: string;
  provider_avatar?: string;
  provider_bio: string;
  provider_location: string;
  provider_languages: string[];
  provider_response_time: string;
  provider_completed_projects: number;
  rating: number;
  review_count: number;
  delivery_time: string;
  tags: string[];
  whats_included: string[];
  requirements: string[];
  portfolio: { title: string; image: string; description: string }[];
  reviews: { author: string; avatar: string; rating: number; date: string; comment: string }[];
}

export interface ServiceBooking {
  id: string;
  service_id: string;
  service_title: string;
  provider_name: string;
  status: 'pending' | 'accepted' | 'in_progress' | 'completed' | 'cancelled';
  agreed_price: number;
  currency: string;
  deadline: string;
  requirements: string;
  created_at: string;
}

export interface ServiceProvider {
  id: string;
  name: string;
  avatar?: string;
  company: string;
  bio: string;
  expertise: string[];
  rating: number;
  completed_projects: number;
  response_time: string;
}

